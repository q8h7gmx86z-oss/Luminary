// The evidence behind every game and task in Luminary.
//
// Rules for this file:
// - Every paper here was checked against its PubMed record or the publisher's page (November 2026).
//   Never add a paper, DOI or number from memory. Look it up, then add it.
// - Highlights state what the paper found, in plain English, with its own numbers.
// - Say where the evidence is weak or mixed. Users should never have to take our word for it.

export type Paper = {
  id: string;
  /** Short citation, e.g. "Edwards et al. 2017". */
  short: string;
  authors: string;
  year: number;
  title: string;
  journal: string;
  /** Volume, issue and pages as printed. */
  ref: string;
  doi?: string;
  pmid?: string;
  /** What kind of study, and how big. */
  design: string;
  /** The headline result, in plain English. */
  finding: string;
};

export type Verdict = 'strong' | 'moderate' | 'mixed' | 'early' | 'measure';

export const VERDICTS: Record<Verdict, { label: string; explain: string }> = {
  strong: { label: 'Strong evidence', explain: 'Large trials or meta-analyses agree.' },
  moderate: { label: 'Good evidence', explain: 'Solid studies, with limits on how far the result reaches.' },
  mixed: { label: 'Mixed evidence', explain: 'It improves the trained skill. Wider benefits are disputed.' },
  early: { label: 'Early evidence', explain: 'Promising, but small studies or indirect support.' },
  measure: { label: 'Established test', explain: 'A standard research task. The evidence is for what it measures.' },
};

export type Quote = { text: string; who: string; role: string; source: string };

export type Evidence = {
  id: string;
  name: string;
  kind: 'game' | 'task' | 'habit';
  verdict: Verdict;
  /** One line: why this is in your training. */
  why: string;
  /** Two to four plain-English highlights from the papers. */
  highlights: string[];
  /** What the research does not show. Always present. */
  limits: string;
  papers: string[];
  quote?: string;
};

export function paperUrl(p: Paper): string {
  if (p.doi) return `https://doi.org/${p.doi}`;
  return `https://pubmed.ncbi.nlm.nih.gov/${p.pmid}/`;
}

export function pubmedUrl(p: Paper): string | undefined {
  return p.pmid ? `https://pubmed.ncbi.nlm.nih.gov/${p.pmid}/` : undefined;
}

